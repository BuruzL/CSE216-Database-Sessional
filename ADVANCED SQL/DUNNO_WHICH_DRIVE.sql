SELECT E.EMPLOYEE_ID,
e.first_name || ' ' || e.last_name AS full_name
, E.SALARY, D.DEPARTMENT_NAME, J.JOB_TITLE
FROM EMPLOYEES E 
JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID 
JOIN JOBS J 
ON J.JOB_ID=E.JOB_ID 
WHERE (
    SELECT COUNT(*)
    FROM EMPLOYEES E2
    WHERE E.DEPARTMENT_ID=E2.DEPARTMENT_ID
)>=2
AND E.SALARY=(
    SELECT MAX(E4.SALARY)
    FROM EMPLOYEES E4 
    WHERE E4.DEPARTMENT_ID=E.DEPARTMENT_ID 
    AND E4.SALARY<(
        SELECT MAX(E5.SALARY)
        FROM EMPLOYEES E5 
        WHERE E5.DEPARTMENT_ID=E.DEPARTMENT_ID
    )
)
ORDER BY E.SALARY DESC,
         D.DEPARTMENT_NAME ASC,
         E.EMPLOYEE_ID ASC;

