SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.SALARY 
FROM EMPLOYEES E 
JOIN DEPARTMENTS D 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
JOIN LOCATIONS L
ON L.LOCATION_ID=D.LOCATION_ID
WHERE (
   ((
    SELECT M.SALARY
    FROM EMPLOYEES M 
    WHERE E.MANAGER_ID=M.EMPLOYEE_ID
   )>15000 AND NOT
   (
    L.CITY='SEATLE'
   ))
   OR(
    (
        L.CITY= 'SEATLE'
    )AND NOT(
        SELECT M.SALARY
    FROM EMPLOYEES M 
    WHERE E.MANAGER_ID=M.EMPLOYEE_ID
   )>15000 
    )
   )

ORDER BY E.SALARY DESC, E.EMPLOYEE_ID ASC;


