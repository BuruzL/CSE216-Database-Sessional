SELECT E.EMPLOYEE_ID, E.FIRST_NAME, D.DEPARTMENT_NAME,E.SALARY,
(CASE 
WHEN E.HIRE_DATE< DATE '2005-01-01' THEN 'VETERAN'
WHEN EXTRACT(YEAR FROM E.HIRE_DATE) BETWEEN 2005 AND 2007 THEN 'MID'
WHEN EXTRACT(YEAR FROM E.HIRE_DATE)>=2008 THEN 'RECENT'
END ) AS TENURE_CATAGORY
FROM EMPLOYEES E 
JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID 
WHERE E.SALARY>(
    SELECT AVG(EE.SALARY)
    FROM EMPLOYEES EE
)

UNION 
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, D.DEPARTMENT_NAME,E.SALARY,
(CASE 
WHEN E.HIRE_DATE< DATE '2005-01-01' THEN 'VETERAN'
WHEN EXTRACT(YEAR FROM E.HIRE_DATE) BETWEEN 2005 AND 2007 THEN 'MID'
WHEN EXTRACT(YEAR FROM E.HIRE_DATE)>=2008 THEN 'RECENT'
END ) AS TENURE_CATAGORY
FROM EMPLOYEES E 
JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID 
WHERE EXISTS(
    SELECT 1 
    FROM JOB_HISTORY JH 
    WHERE E.EMPLOYEE_ID=JH.EMPLOYEE_ID
)
ORDER BY SALARY DESC;
