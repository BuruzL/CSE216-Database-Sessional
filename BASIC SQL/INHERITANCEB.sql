QUES 1
  
SELECT 
SUBSTR(PHONE_NUMBER,1, INSTR(PHONE_NUMBER, '.')-1) AS COUNTRY_CODE,
COUNT(*) AS NUMBER_OF_EMPLOYEES
FROM EMPLOYEES 
WHERE HIRE_DATE> DATE '2005-01-01'
GROUP BY SUBSTR(PHONE_NUMBER, 1, INSTR(PHONE_NUMBER, '.')-1);


