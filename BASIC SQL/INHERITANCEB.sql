QUES 4

SELECT DEPARTMENT_ID,
TO_CHAR(SUM(SALARY*12), '99,999,999') AS TOTAL_PAYOUT
FROM EMPLOYEES 
GROUP BY DEPARTMENT_ID
HAVING COUNT(*)>=1
AND MIN(SALARY)>=2500;

QUES 5
SELECT EMPLOYEE_ID, 
(UPPER(SUBSTR(FIRST_NAME,1,2))||LENGTH(LAST_NAME)||SUBSTR(PHONE_NUMBER,-1)) AS SECURITY_CODE
FROM EMPLOYEES
WHERE LENGTH(FIRST_NAME)>LENGTH(LAST_NAME)
ORDER BY LENGTH(SECURITY_CODE) DESC;
