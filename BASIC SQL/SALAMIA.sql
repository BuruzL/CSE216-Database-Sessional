SELECT COUNTRY_ID,
case
WHEN STREET_ADDRESS IS NOT NULL
AND CITY IS NOT NULL 
AND STATE_PROVINCE IS NOT NULL 
AND POSTAL_CODE IS NOT NULL 
THEN '(' || STREET_ADDRESS||','||CITY||','||STATE_PROVINCE||'-'||POSTAL_CODE||')'
ELSE null
END AS ADDRESS 
FROM LOCATIONS
ORDER BY 
COUNTRY_ID ASC,
POSTAL_CODE DESC;

