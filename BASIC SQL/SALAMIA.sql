SALAMI QUES 1
SELECT 
CASE 
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 1 AND 4 THEN 'FIRST_QUARTER'
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 5 AND 8 THEN 'SECOND_QUARTER'
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 9 AND 12 THEN 'THIRD_QUARTER'
    END AS QUARTER, COUNT(*) AS CNT
FROM EMPLOYEES
GROUP BY CASE 
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 1 AND 4 THEN 'FIRST_QUARTER'
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 5 AND 8 THEN 'SECOND_QUARTER'
    WHEN TO_NUMBER(TO_CHAR(HIRE_DATE, 'MM')) BETWEEN 9 AND 12 THEN 'THIRD_QUARTER'
    END
ORDER BY QUARTER;


